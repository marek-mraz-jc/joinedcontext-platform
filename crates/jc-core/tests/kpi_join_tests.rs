//! The compiled `kpi` mapping of the example is the one `bento test` runs (PL-104, T-4864).
//!
//! `examples/ingestion/kpi-parking-per-stop/bento.yaml` carries the mapping jc-core renders for
//! its pipeline.yaml, and CI's pipelines lane runs its golden tests through Bento. This test keeps
//! the two the same: `JC_UPDATE_GOLDEN=1 cargo test -p jc-core --test kpi_join_tests` rewrites it.

use jc_core::kinds::{Pipeline, Step};
use jc_core::kpi_join::{self, Target};
use std::path::PathBuf;

fn example() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../examples/ingestion/kpi-parking-per-stop")
}

fn rendered() -> String {
    let text = std::fs::read_to_string(example().join("pipeline.yaml")).expect("pipeline.yaml");
    let pipeline = Pipeline::from_yaml(&text).expect("parses");
    pipeline.validate().expect("valid");
    let Some(Step::Compute(compute)) = pipeline.spec.steps.first() else {
        panic!("the example's step is a kpi compute");
    };
    let step = compute.kpi.as_ref().expect("kpi");
    let mut inputs = pipeline.spec.kpi_inputs().expect("inputs");
    for input in &mut inputs {
        input.endpoint = format!(
            "helsinki-{}",
            if input.name == "parking" {
                "parking"
            } else {
                "transit"
            }
        );
    }
    let expr = step.validate(&inputs).expect("checks");
    let mapping = kpi_join::bloblang(
        step,
        &expr,
        &inputs,
        &Target {
            pipeline_space: "helsinki",
            pipeline: "parking-per-stop",
        },
    );
    let mut out = String::from(
        "# Generated by jc-core kpi_join::bloblang from pipeline.yaml (T-4864); do not edit:\n\
         # JC_UPDATE_GOLDEN=1 cargo test -p jc-core --test kpi_join_tests rewrites it.\n\
         pipeline:\n  processors:\n    - mapping: |\n",
    );
    for line in mapping.lines() {
        out.push_str("        ");
        out.push_str(line);
        out.push('\n');
    }
    out
}

#[test]
fn the_example_runs_the_mapping_jc_core_compiles() {
    let path = example().join("bento.yaml");
    let want = rendered();
    if std::env::var_os("JC_UPDATE_GOLDEN").is_some() {
        std::fs::write(&path, &want).expect("writes");
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert_eq!(
        have, want,
        "bento.yaml is stale: rerun with JC_UPDATE_GOLDEN=1"
    );
}

fn manifest(edit: impl Fn(&mut serde_json::Value)) -> Result<(), String> {
    let text = std::fs::read_to_string(example().join("pipeline.yaml")).expect("pipeline.yaml");
    let mut value: serde_json::Value = serde_norway::from_str(&text).expect("yaml");
    edit(&mut value);
    let pipeline: Pipeline = serde_json::from_value(value).map_err(|e| e.to_string())?;
    pipeline.validate().map_err(|e| e.to_string())
}

#[test]
fn admission_refuses_a_kpi_step_its_sources_cannot_feed() {
    assert_eq!(manifest(|_| {}), Ok(()));
    let unnamed = manifest(|p| {
        if let Some(source) = p["spec"]["sources"][1].as_object_mut() {
            source.remove("name");
        }
    });
    assert!(unnamed.is_err_and(|e| e.contains("has a `name`")));
    let unknown = manifest(|p| p["spec"]["steps"][0]["kpi"]["formula"] = "sum(cars.x)".into());
    assert!(unknown.is_err_and(|e| e.contains("`cars` is not a source")));
    let second_step = manifest(|p| {
        let step = p["spec"]["steps"][0].clone();
        if let Some(steps) = p["spec"]["steps"].as_array_mut() {
            steps.push(step);
        }
    });
    assert!(second_step.is_err_and(|e| e.contains("only step")));
    let without_kpi = manifest(|p| {
        if let Some(step) = p["spec"]["steps"][0].as_object_mut() {
            step.remove("kpi");
        }
    });
    assert!(without_kpi.is_err_and(|e| e.contains("carries `kpi`")));
    let bad_name = manifest(|p| p["spec"]["sources"][0]["name"] = "Parking Sites".into());
    assert!(bad_name.is_err());
}
