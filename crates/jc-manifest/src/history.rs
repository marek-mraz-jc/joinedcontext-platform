//! `spec.history` (PL-106…PL-109) compiled into one Bloblang step and checked against the space's
//! model: the step runs after the author's steps and before the lifetime step, and sets or removes
//! the `observedAt` of every instance of each planned attribute (PL-107). `keep` reaches the broker
//! through the space's retention document, which the Portal's reconciler writes (PL-108).
//!
//! The text is generated from checked parts only: types match the entity-type pattern and names
//! the slot pattern; every string enters the text as a JSON literal, never as code.

use jc_core::error::{Error, Result};
use jc_core::kinds::pipeline_history::RECEIVED;
use jc_core::kinds::pipeline_lifetime::is_slot_name;
use jc_core::kinds::PipelineSpec;

use crate::model_schema::ModelSchema;

/// The model checks of PL-106 at proposal time: each type a class of the space's model, each name
/// one of its slots, each `observedAt` a date-time slot of the type or `received`.
pub fn check(spec: &PipelineSpec, model: &ModelSchema) -> Result<()> {
    for (index, entry) in spec.history.iter().enumerate() {
        let path = format!("spec.history[{index}]");
        let Some(class) = model.attributes(&entry.entity_type) else {
            return Err(Error::Invalid {
                field: format!("{path}.type"),
                reason: format!(
                    "the space's model declares no class `{}` (PL-106)",
                    entry.entity_type
                ),
            });
        };
        let slot = |name: &str| class.attributes.iter().find(|a| a.name == name);
        for (at, attribute) in entry.attributes.iter().enumerate() {
            let at = format!("{path}.attributes[{at}]");
            if let Some(name) = attribute.names.iter().find(|name| slot(name).is_none()) {
                return Err(Error::Invalid {
                    field: format!("{at}.names"),
                    reason: format!(
                        "`{name}` is not a slot of `{}` in the space's model {} {} (PL-106)",
                        entry.entity_type, class.model, class.version
                    ),
                });
            }
            match attribute.observed_at.as_deref() {
                None | Some(RECEIVED) => {}
                Some(field) => {
                    if slot(field).and_then(|a| a.format.as_deref()) != Some("date-time") {
                        return Err(Error::Invalid {
                            field: format!("{at}.observedAt"),
                            reason: format!(
                                "`{field}` is not a date-time slot of `{}`; name one, or \
                                 `received` (PL-106)",
                                entry.entity_type
                            ),
                        });
                    }
                }
            }
        }
    }
    Ok(())
}

/// The step that sets each planned `observedAt` (PL-107), `None` when no entry plans one. It
/// takes a message holding one entity or an array of entities; a type without an entry passes
/// unchanged. The output is the same for the same manifest: entries by type, names sorted.
pub fn step(spec: &PipelineSpec) -> Result<Option<String>> {
    let mut entries: Vec<(&str, Vec<(&str, &str)>)> = Vec::new();
    for entry in &spec.history {
        let mut planned: Vec<(&str, &str)> = Vec::new();
        for attribute in &entry.attributes {
            let Some(from) = attribute.observed_at.as_deref() else {
                continue;
            };
            for name in &attribute.names {
                if !is_slot_name(name) || (from != RECEIVED && !is_slot_name(from)) {
                    return Err(Error::Invalid {
                        field: "spec.history".to_owned(),
                        reason: format!("`{}` is not a slot name (PL-106)", name.escape_debug()),
                    });
                }
                planned.push((name, from));
            }
        }
        if !planned.is_empty() {
            planned.sort();
            entries.push((&entry.entity_type, planned));
        }
    }
    if entries.is_empty() {
        return Ok(None);
    }
    entries.sort();
    let mut text = String::from(
        "# spec.history (PL-106, PL-107), generated by jcctl: the time of each planned row, after \
         the author's steps.\n\
         map jc_history {\n  root = this\n",
    );
    for (entity_type, planned) in entries {
        text.push_str(&format!("  if this.type == {} {{\n", literal(entity_type)));
        for (name, from) in planned {
            text.push_str(&block(name, from));
        }
        text.push_str("  }\n");
    }
    text.push_str(
        "}\n\
         root = if this.type() == \"array\" { this.map_each(e -> if e.type() == \"object\" { \
         e.apply(\"jc_history\") } else { e }) } else if this.type() == \"object\" { \
         this.apply(\"jc_history\") } else { this }\n",
    );
    Ok(Some(text))
}

/// Sets `observedAt` of every instance of `name` from the slot `from`, or removes it for
/// `received`; a slot that gives no date-time leaves the attribute without one (PL-107).
fn block(name: &str, from: &str) -> String {
    let time = match from {
        RECEIVED => "null".to_owned(),
        slot => format!(
            "this.{slot}.(a -> if a.type() == \"array\" {{ a.index(0).catch(null) }} else {{ a }})\
             .value.(v -> if v.type() == \"object\" {{ v.\"@value\" }} else {{ v }})\
             .ts_parse(\"2006-01-02T15:04:05Z07:00\").ts_format(\"2006-01-02T15:04:05.999999999Z07:00\", \"UTC\")\
             .catch(null)"
        ),
    };
    format!(
        "    if this.exists({key}) {{\n      let at = {time}\n      root.{name} = \
         this.{name}.(a -> if a.type() == \"array\" {{ a.map_each(i -> if i.type() == \"object\" \
         {{ if $at != null {{ i.assign({{\"observedAt\": $at}}) }} else {{ i.without(\"observedAt\") \
         }} }} else {{ i }}) }} else if a.type() == \"object\" {{ if $at != null {{ \
         a.assign({{\"observedAt\": $at}}) }} else {{ a.without(\"observedAt\") }} }} else {{ a }})\n    }}\n",
        key = literal(name),
    )
}

/// A Bloblang string literal: JSON's quoting is Bloblang's.
fn literal(text: &str) -> String {
    serde_json::Value::String(text.to_owned()).to_string()
}
