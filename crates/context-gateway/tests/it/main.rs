//! context-gateway's integration tests as one binary (T-6077): 179 files in one link, where each
//! was a binary of its own. Run one file with a filter:
//! `cargo test -p context-gateway --test it projection_tests::`.
//!
//! Seven stay binaries of their own, because each needs the process to itself:
//! - the measurement rigs `ws_fanout_rig` (it raises the per-space socket cap, which the gateway
//!   reads once per process) and `ws_abuse_rig`;
//! - the memory tests `in_flight_tests` and `sweep_memory_tests`, whose counting global
//!   allocator would count every other test's bytes;
//! - `mcp_activity_tests` and `rate_limit_activity_tests`, which drain the process's activity
//!   tally that every MCP call here adds to;
//! - `mcp_broker_limits_tests`, which sets the process's broker page limits.

